// ======================================================
// POST /api/employees
// Create employee profile and login account.
// ======================================================

router.post("/", requireAdminOrHR, async (req, res, next) => {
  let createdUser = null;

  try {
    const payload = cleanPayload(req.body);
    const validationError = validatePayload(payload, true);

    if (validationError) {
      return res.status(400).json({
        success: false,
        message: validationError,
      });
    }

    if (!payload.email) {
      return res.status(400).json({
        success: false,
        message: "Employee email is required",
      });
    }

    const password =
      typeof req.body.password === "string"
        ? req.body.password
        : "";

    if (password.length < 8) {
      return res.status(400).json({
        success: false,
        message:
          "Temporary password must be at least 8 characters",
      });
    }

    const existingUser = await User.findOne({
      email: payload.email,
    }).select("_id role");

    if (existingUser) {
      return res.status(409).json({
        success: false,
        message:
          "An account already exists with this email. Use a different email.",
      });
    }

    payload.employeeId = await generateEmployeeId();

    createdUser = await User.create({
      name: payload.name,
      email: payload.email,
      passwordHash: await bcrypt.hash(password, 12),
      role: "employee",
    });

    payload.userId = createdUser._id;

    const employee = await Employee.create(payload);

    return res.status(201).json({
      success: true,
      data: employee,
      message:
        "Employee profile and login account created successfully",
    });
  } catch (error) {
    // Remove the newly created account if profile creation fails.
    if (createdUser?._id) {
      try {
        await User.findByIdAndDelete(createdUser._id);
      } catch (cleanupError) {
        console.error(
          "Could not clean up employee account:",
          cleanupError.message
        );
      }
    }

    if (error.code === 11000) {
      return res.status(409).json({
        success: false,
        message: "Duplicate employee ID or email detected",
      });
    }

    next(error);
  }
});

// ======================================================
// PUT /api/employees/:id
// Update employee details.
// ======================================================

router.put("/:id", requireAdminOrHR, async (req, res, next) => {
  try {
    if (!mongoose.isValidObjectId(req.params.id)) {
      return res.status(400).json({
        success: false,
        message: "Invalid employee id",
      });
    }

    const payload = cleanPayload(req.body);
    const validationError = validatePayload(payload);

    if (validationError) {
      return res.status(400).json({
        success: false,
        message: validationError,
      });
    }

    const employee = await Employee.findByIdAndUpdate(
      req.params.id,
      { $set: payload },
      { new: true, runValidators: true }
    );

    if (!employee) {
      return res.status(404).json({
        success: false,
        message: "Employee not found",
      });
    }

    return res.json({
      success: true,
      data: employee,
      message: "Employee updated successfully",
    });
  } catch (error) {
    if (error.code === 11000) {
      return res.status(409).json({
        success: false,
        message: "Duplicate employee data detected",
      });
    }

    next(error);
  }
});

