// GET /api/employees/me
// Logged-in employee can view their own profile.
// ======================================================

router.get("/me", async (req, res, next) => {
  try {
    if (req.user.role !== "employee") {
      return res.status(403).json({
        success: false,
        message: "This endpoint is for employee accounts only",
      });
    }

    let employee = await Employee.findOne({
      userId: req.user.id,
    });

    // Link an existing employee record by email if needed.
    if (!employee && req.user.email) {
      employee = await Employee.findOne({
        email: String(req.user.email).trim().toLowerCase(),
        $or: [{ userId: { $exists: false } }, { userId: null }],
      });

      if (employee) {
        employee.userId = req.user.id;
        await employee.save();
      }
    }

    if (!employee) {
      return res.status(404).json({
        success: false,
        message:
          "Employee profile not found. Ask Admin/HR to check your employee record.",
      });
    }

    return res.json({
      success: true,
      data: employee,
    });
  } catch (error) {
    next(error);
  }
});

