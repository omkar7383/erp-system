// GET /api/employees/:id/face-enrollment
// Returns enrollment status, never the descriptor.
// ======================================================

router.get(
  "/:id/face-enrollment",
  requireAdminOrHR,
  async (req, res, next) => {
    try {
      if (!mongoose.isValidObjectId(req.params.id)) {
        return res.status(400).json({
          success: false,
          message: "Invalid employee id",
        });
      }

      const employee = await Employee.findById(req.params.id)
        .select(
          [
            "name",
            "employeeId",
            "faceEnrollment.status",
            "faceEnrollment.provider",
            "faceEnrollment.enrolledAt",
            "faceEnrollment.lastVerifiedAt",
            "faceEnrollment.enrollmentVersion",
            "biometricConsent.given",
            "biometricConsent.consentedAt",
            "biometricConsent.consentVersion",
          ].join(" ")
        )
        .lean();

      if (!employee) {
        return res.status(404).json({
          success: false,
          message: "Employee not found",
        });
      }

      return res.json({
        success: true,
        data: {
          employeeId: employee._id,
          name: employee.name,
          faceEnrollment: employee.faceEnrollment || {
            status: "Not Enrolled",
          },
          biometricConsent: employee.biometricConsent || {
            given: false,
          },
        },
      });
    } catch (error) {
      next(error);
    }
  }
);

// ======================================================
// POST /api/employees/:id/face-enrollment
//
// Expected JSON:
// {
//   "faceDescriptor": [128 numeric values],
//   "consentGiven": true,
//   "consentVersion": "v1",
//   "provider": "face-api.js"
// }
//
// The descriptor must be generated by a compatible
// face-recognition model on the client or server.
// ======================================================

router.post(
  "/:id/face-enrollment",
  requireAdminOrHR,
  async (req, res, next) => {
    try {
      if (!mongoose.isValidObjectId(req.params.id)) {
        return res.status(400).json({
          success: false,
          message: "Invalid employee id",
        });
      }

      const {
        faceDescriptor,
        consentGiven,
        consentVersion,
        provider,
      } = req.body || {};

      if (consentGiven !== true) {
        return res.status(400).json({
          success: false,
          message:
            "Employee biometric consent is required before enrollment",
        });
      }

      if (!validateFaceDescriptor(faceDescriptor)) {
        return res.status(400).json({
          success: false,
          message:
            "A valid 128-value face descriptor is required. A camera image alone is not a face descriptor.",
        });
      }

      const employee = await Employee.findById(req.params.id).select(
        "+faceEnrollment.faceDescriptor"
      );

      if (!employee) {
        return res.status(404).json({
          success: false,
          message: "Employee not found",
        });
      }

      if (employee.status === "Inactive") {
        return res.status(400).json({
          success: false,
          message:
            "Inactive employees cannot enroll for attendance",
        });
      }

      const now = new Date();

      const previousEnrollmentVersion = Number(
        employee.faceEnrollment?.enrollmentVersion || 0
      );

      employee.faceEnrollment = {
        status: "Enrolled",

        provider:
          typeof provider === "string" && provider.trim()
            ? provider.trim().slice(0, 80)
            : "face-api.js",

        faceDescriptor,

        enrolledAt: now,

        enrollmentVersion: previousEnrollmentVersion + 1,

        lastVerifiedAt:
          employee.faceEnrollment?.lastVerifiedAt || null,
      };

      employee.biometricConsent = {
        given: true,
        consentedAt: now,

        consentVersion:
          typeof consentVersion === "string" &&
          consentVersion.trim()
            ? consentVersion.trim().slice(0, 40)
            : "v1",
      };

      await employee.save();

      return res.status(200).json({
        success: true,
        message:
          "Face enrollment and biometric consent saved successfully",

        data: {
          employeeId: employee._id,

          faceEnrollment: {
            status: employee.faceEnrollment.status,
            provider: employee.faceEnrollment.provider,
            enrolledAt: employee.faceEnrollment.enrolledAt,
            enrollmentVersion:
              employee.faceEnrollment.enrollmentVersion,
          },

          biometricConsent: {
            given: employee.biometricConsent.given,
            consentedAt: employee.biometricConsent.consentedAt,
            consentVersion:
              employee.biometricConsent.consentVersion,
          },
        },
      });
    } catch (error) {
      next(error);
    }
  }
);

