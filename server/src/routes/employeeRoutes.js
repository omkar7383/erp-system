// Only Admin and HR can manage employee records.
function requireAdminOrHR(req, res, next) {
  if (!["admin", "hr"].includes(req.user?.role)) {
    return res.status(403).json({
      success: false,
      message: "You are not allowed to manage employee records",
    });
  }

  next();
}

// Allow only supported employee fields.
function cleanPayload(body = {}) {
  const allowed = [
    "name",
    "email",
    "phone",
    "department",
    "designation",
    "joiningDate",
    "employmentType",
    "status",
    "salary",
  ];

  const payload = {};

  for (const key of allowed) {
    if (body[key] !== undefined) {
      payload[key] = body[key];
    }
  }

  const stringFields = [
    "name",
    "email",
    "phone",
    "department",
    "designation",
    "joiningDate",
    "employmentType",
    "status",
  ];

  for (const key of stringFields) {
    if (payload[key] !== undefined) {
      payload[key] = String(payload[key]).trim();
    }
  }

  if (payload.email) {
    payload.email = payload.email.toLowerCase();
  }

  if (payload.salary !== undefined) {
    payload.salary =
      payload.salary === "" || payload.salary === null
        ? NaN
        : Number(payload.salary);
  }

  return payload;
}

// Generate sequential employee IDs.
async function generateEmployeeId() {
  const employees = await Employee.find({
    employeeId: /^EMP-\d+$/,
  })
    .select("employeeId")
    .lean();

  const highest = employees.reduce((max, employee) => {
    const match = employee.employeeId?.match(/^EMP-(\d+)$/);

    return Math.max(max, match ? Number(match[1]) : 0);
  }, 0);

  const counters = mongoose.connection.collection("counters");

  await counters.updateOne(
    { _id: "employeeId" },
    { $max: { seq: highest } },
    { upsert: true }
  );

  const result = await counters.findOneAndUpdate(
    { _id: "employeeId" },
    { $inc: { seq: 1 } },
    {
      returnDocument: "after",
      includeResultMetadata: false,
    }
  );

  const counter = result?.value ?? result;

  if (!counter || !Number.isSafeInteger(counter.seq)) {
    throw new Error("Could not generate employee ID");
  }

  return `EMP-${String(counter.seq).padStart(3, "0")}`;
}

// Validate employee data.
function validatePayload(payload, isCreate = false) {
  if (isCreate && !payload.name) {
    return "Employee name is required";
  }

  if (payload.name !== undefined && !payload.name) {
    return "Employee name cannot be empty";
  }

  if (
    payload.email !== undefined &&
    !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(payload.email)
  ) {
    return "Please enter a valid email address";
  }

  if (
    payload.salary !== undefined &&
    (!Number.isFinite(payload.salary) || payload.salary < 0)
  ) {
    return "Salary must be a valid non-negative number";
  }

  if (
    payload.employmentType !== undefined &&
    !["Full-time", "Part-time", "Intern", "Contract"].includes(
      payload.employmentType
    )
  ) {
    return "Invalid employment type";
  }

  if (
    payload.status !== undefined &&
    !["Active", "On Leave", "Inactive"].includes(payload.status)
  ) {
    return "Invalid employee status";
  }

  return null;
}

// Validate a face descriptor generated by a face-recognition model.
function validateFaceDescriptor(descriptor) {
  return (
    Array.isArray(descriptor) &&
    descriptor.length === 128 &&
    descriptor.every(
      (value) => typeof value === "number" && Number.isFinite(value)
    )
  );
}

